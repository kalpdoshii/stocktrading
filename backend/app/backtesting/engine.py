"""
engine.py — Backtesting Engine v2
====================================
Simulates trades over historical data with modular strategies, realistic
execution timing, configurable position sizing, and proper transaction costs.

Key improvements over v1:
  1. **No Look-Ahead Bias**: Signals generated from day-*t* data are executed
     at day-(*t+1*) open by default, not day-*t* close.
  2. **Modular Strategies**: Plug any strategy implementing ``BaseStrategy``.
  3. **Position Sizing**: ``all_in`` | ``fixed_fraction`` | ``volatility_adjusted``.
  4. **Execution Timing**: ``next_open`` (default, realistic) | ``same_close``
     (legacy, for comparison only).

No short selling or leverage.  Indian equity-delivery transaction costs
are applied by default.

Usage:
    from app.backtesting.engine import run_backtest
    results = run_backtest("RELIANCE.NS", strategy_name="sma_crossover")
"""

from __future__ import annotations

import logging
from datetime import date, timedelta
from typing import Any, Optional

import numpy as np
import pandas as pd
import yfinance as yf
from sqlalchemy.orm import Session

from app.config import INDIAN_EQUITY_COSTS, STARTING_CAPITAL
from app.features.builder import (
    BASELINE_FEATURES,
    SENTIMENT_FEATURES,
    load_price_data,
    load_sentiment_data,
)
from app.features.technical import compute_indicators

logger = logging.getLogger(__name__)

# Valid execution timing modes
EXECUTION_TIMING = ("next_open", "same_close")
# Valid position sizing modes
POSITION_SIZING_MODES = ("all_in", "fixed_fraction", "volatility_adjusted")

# Disclaimer text attached to every result
BACKTEST_DISCLAIMER = (
    "SIMULATED RESULTS — NOT INDICATIVE OF FUTURE PERFORMANCE. "
    "These results are generated by a historical backtest engine using "
    "past data.  They do NOT reflect actual trading, real transaction "
    "costs may differ, and market conditions change.  Do NOT treat these "
    "results as investment advice."
)


def run_backtest(
    ticker: str,
    *,
    strategy_name: str = "ml_signal",
    strategy_params: Optional[dict[str, Any]] = None,
    model_version: str = "sentiment_v1",
    start_date: Optional[date] = None,
    end_date: Optional[date] = None,
    initial_capital: float = STARTING_CAPITAL,
    transaction_costs: Optional[dict] = None,
    execution_timing: str = "next_open",
    position_sizing: str = "all_in",
    position_fraction: float = 0.20,
    volatility_lookback: int = 20,
    target_annual_vol: float = 0.15,
) -> dict:
    """
    Run a backtest simulation for a ticker.

    Args:
        ticker:              Stock symbol (e.g. ``"RELIANCE.NS"``).
        strategy_name:       Key in ``STRATEGY_REGISTRY`` (default ``"ml_signal"``).
        strategy_params:     Extra keyword args forwarded to the strategy constructor.
        model_version:       ML model version (only used by ``ml_signal`` strategy).
        start_date / end_date: Clip the backtest period.
        initial_capital:     Starting cash.
        transaction_costs:   Cost structure dict (default: Indian equity delivery).
        execution_timing:    ``"next_open"`` (realistic, default) or
                             ``"same_close"`` (legacy, look-ahead).
        position_sizing:     ``"all_in"`` | ``"fixed_fraction"`` | ``"volatility_adjusted"``.
        position_fraction:   Fraction of equity per trade (for ``fixed_fraction``).
        volatility_lookback: Window for daily vol estimate (for ``volatility_adjusted``).
        target_annual_vol:   Annual volatility target (for ``volatility_adjusted``).

    Returns:
        dict with keys: ticker, strategy, metrics, equity_curve, trades, disclaimer.
    """
    if execution_timing not in EXECUTION_TIMING:
        raise ValueError(
            f"execution_timing must be one of {EXECUTION_TIMING}, "
            f"got '{execution_timing}'"
        )
    if position_sizing not in POSITION_SIZING_MODES:
        raise ValueError(
            f"position_sizing must be one of {POSITION_SIZING_MODES}, "
            f"got '{position_sizing}'"
        )

    logger.info(
        f"Backtest {ticker} | strategy={strategy_name} "
        f"| execution={execution_timing} | sizing={position_sizing}"
    )

    # ------------------------------------------------------------------
    # Step 1: Load data, compute features, merge sentiment
    # ------------------------------------------------------------------
    df = load_price_data(ticker)
    if df.empty:
        raise ValueError(f"No price data for {ticker}")

    df = compute_indicators(df)

    # Merge sentiment for ML strategy
    if strategy_name == "ml_signal":
        sentiment_df = load_sentiment_data(ticker)
        if not sentiment_df.empty:
            df = df.merge(sentiment_df, on="date", how="left")
            for col in SENTIMENT_FEATURES:
                if col in df.columns:
                    df[col] = df[col].ffill().fillna(0.0)

    # Ensure "open" column exists for next_open execution
    if "open" not in df.columns:
        logger.warning(
            "No 'open' column found; falling back to 'close' for open prices."
        )
        df["open"] = df["close"]

    # Drop NaN indicator warm-up rows
    indicator_cols = [c for c in df.columns if c not in ("date", "ticker")]
    df_clean = df.dropna(subset=[c for c in indicator_cols if c in df.columns]).copy()

    # Apply date filters
    if start_date:
        df_clean = df_clean[df_clean["date"] >= start_date]
    if end_date:
        df_clean = df_clean[df_clean["date"] <= end_date]

    if len(df_clean) < 10:
        raise ValueError(f"Not enough data for backtest ({len(df_clean)} rows)")

    df_clean = df_clean.reset_index(drop=True)

    # ------------------------------------------------------------------
    # Step 2: Instantiate strategy and generate signals
    # ------------------------------------------------------------------
    from app.backtesting.strategies import get_strategy

    params: dict[str, Any] = dict(strategy_params or {})
    if strategy_name == "ml_signal":
        params.setdefault("model_version", model_version)
    strategy = get_strategy(strategy_name, **params)

    raw_signals = strategy.generate_signals(df_clean)

    # Execution‐timing alignment:
    # - "next_open": Signal from bar i  →  execution at bar i+1 open.
    #   We shift signals forward by 1 so that the executed signal on bar i
    #   was actually generated from bar i-1.
    # - "same_close": Legacy behavior — execute at the same bar's close.
    if execution_timing == "next_open":
        # Shift signals by 1: the first bar has no actionable signal.
        aligned_signals = raw_signals.shift(1).fillna("HOLD")
    else:
        aligned_signals = raw_signals

    df_clean["signal"] = aligned_signals.values

    # ------------------------------------------------------------------
    # Step 3: Simulate trades
    # ------------------------------------------------------------------
    equity_curve, trades = _simulate_trades(
        df_clean,
        initial_capital=initial_capital,
        transaction_costs=transaction_costs or INDIAN_EQUITY_COSTS,
        execution_timing=execution_timing,
        position_sizing=position_sizing,
        position_fraction=position_fraction,
        volatility_lookback=volatility_lookback,
        target_annual_vol=target_annual_vol,
    )

    # ------------------------------------------------------------------
    # Step 4: Compute metrics
    # ------------------------------------------------------------------
    from app.backtesting.metrics import compute_metrics

    metrics = compute_metrics(equity_curve, trades, initial_capital)

    benchmark_return = _fetch_nifty_return(
        df_clean["date"].iloc[0],
        df_clean["date"].iloc[-1],
    )
    metrics["benchmark_return_pct"] = benchmark_return
    metrics["excess_return_pct"] = (
        round(metrics["total_return_pct"] - benchmark_return, 2)
        if benchmark_return is not None
        else None
    )

    result = {
        "ticker": ticker,
        "strategy": {
            "name": strategy_name,
            "params": params,
            "execution_timing": execution_timing,
            "position_sizing": position_sizing,
        },
        "model_version": model_version if strategy_name == "ml_signal" else None,
        "start_date": str(df_clean["date"].iloc[0]),
        "end_date": str(df_clean["date"].iloc[-1]),
        "initial_capital": initial_capital,
        "metrics": metrics,
        "equity_curve": equity_curve,
        "trades": trades,
        "disclaimer": BACKTEST_DISCLAIMER,
    }

    logger.info(
        f"\nBacktest Results for {ticker} ({strategy_name}):\n"
        f"  Period: {result['start_date']} to {result['end_date']}\n"
        f"  Total Return: {metrics['total_return_pct']:.2f}%\n"
        f"  CAGR: {metrics.get('cagr_pct', 'N/A')}%\n"
        f"  Win Rate: {metrics['win_rate']:.2f}%\n"
        f"  Sharpe Ratio: {metrics['sharpe_ratio']:.3f}\n"
        f"  Max Drawdown: {metrics['max_drawdown_pct']:.2f}%\n"
        f"  Total Trades: {metrics['total_trades']}\n"
    )

    return result


# -----------------------------------------------------------------------
# Benchmark fetcher
# -----------------------------------------------------------------------

def _fetch_nifty_return(start: date, end: date) -> float | None:
    """Return buy-and-hold Nifty 50 performance for the backtest period."""
    try:
        prices = yf.download(
            "^NSEI",
            start=str(start),
            end=str(end + timedelta(days=1)),
            progress=False,
            auto_adjust=False,
        )
        if prices.empty:
            return None
        close = prices["Close"]
        if isinstance(close, pd.DataFrame):
            close = close.iloc[:, 0]
        return round((float(close.iloc[-1]) / float(close.iloc[0]) - 1) * 100, 2)
    except Exception as error:
        logger.warning(f"Nifty 50 benchmark unavailable: {error}")
        return None


# -----------------------------------------------------------------------
# Trade Simulation (core)
# -----------------------------------------------------------------------

def _simulate_trades(
    df: pd.DataFrame,
    initial_capital: float,
    transaction_costs: dict,
    execution_timing: str,
    position_sizing: str,
    position_fraction: float,
    volatility_lookback: int,
    target_annual_vol: float,
) -> tuple[list[dict], list[dict]]:
    """
    Long-only trade simulation with modular position sizing.

    Returns:
        (equity_curve, trades)
    """
    cash = initial_capital
    shares = 0
    entry_value = 0.0
    total_costs = 0.0

    equity_curve: list[dict] = []
    trades: list[dict] = []

    # Pre-compute daily volatility for volatility-adjusted sizing
    closes = df["close"].astype(float)
    daily_returns = closes.pct_change()
    rolling_vol = daily_returns.rolling(volatility_lookback, min_periods=5).std()

    for idx in range(len(df)):
        row = df.iloc[idx]
        signal = row["signal"]
        current_date = str(row["date"])

        # Execution price depends on timing mode
        if execution_timing == "next_open":
            exec_price = float(row["open"])
        else:
            exec_price = float(row["close"])

        mark_price = float(row["close"])  # for portfolio valuation

        # ---- Position sizing ----
        def _max_shares_to_buy() -> int:
            """How many shares to buy given sizing mode and available cash."""
            portfolio_value = cash + shares * mark_price
            if position_sizing == "all_in":
                budget = cash
            elif position_sizing == "fixed_fraction":
                budget = min(cash, portfolio_value * position_fraction)
            elif position_sizing == "volatility_adjusted":
                vol = rolling_vol.iloc[idx] if not np.isnan(rolling_vol.iloc[idx]) else 0.02
                daily_target_vol = target_annual_vol / np.sqrt(252)
                # Scale: fraction = daily_target_vol / realized_vol
                frac = min(daily_target_vol / max(vol, 1e-6), 1.0)
                budget = min(cash, portfolio_value * frac)
            else:
                budget = cash

            buy_price = exec_price * (1 + transaction_costs["slippage_rate"])
            if buy_price <= 0:
                return 0
            return int(budget / buy_price)

        # ---- Trading logic ----
        if signal == "BUY" and shares == 0:
            buy_price = exec_price * (1 + transaction_costs["slippage_rate"])
            n_shares = _max_shares_to_buy()
            if n_shares > 0:
                gross_value = n_shares * buy_price
                brokerage = gross_value * transaction_costs["brokerage_rate"]
                exchange = gross_value * transaction_costs["exchange_rate"]
                gst = (brokerage + exchange) * transaction_costs["gst_rate"]
                stamp_duty = gross_value * transaction_costs["stamp_duty_rate"]
                costs = brokerage + exchange + gst + stamp_duty
                cash -= gross_value + costs
                entry_value = gross_value + costs
                total_costs += costs
                shares = n_shares
                trades.append({
                    "date": current_date,
                    "action": "BUY",
                    "price": round(buy_price, 2),
                    "shares": shares,
                    "value": round(gross_value, 2),
                    "costs": round(costs, 2),
                })

        elif signal == "SELL" and shares > 0:
            sell_price = exec_price * (1 - transaction_costs["slippage_rate"])
            gross_value = shares * sell_price
            brokerage = gross_value * transaction_costs["brokerage_rate"]
            stt = gross_value * transaction_costs["stt_rate"]
            exchange = gross_value * transaction_costs["exchange_rate"]
            gst = (brokerage + exchange) * transaction_costs["gst_rate"]
            costs = brokerage + stt + exchange + gst
            revenue = gross_value - costs
            cash += revenue
            pnl = revenue - entry_value
            total_costs += costs
            trades.append({
                "date": current_date,
                "action": "SELL",
                "price": round(sell_price, 2),
                "shares": shares,
                "value": round(gross_value, 2),
                "costs": round(costs, 2),
                "pnl": round(pnl, 2),
            })
            shares = 0
            entry_value = 0.0

        # ---- Record equity (always at close for consistency) ----
        shares_value = shares * mark_price
        portfolio_value = cash + shares_value

        equity_curve.append({
            "date": current_date,
            "portfolio_value": round(portfolio_value, 2),
            "cash": round(cash, 2),
            "shares_value": round(shares_value, 2),
            "transaction_costs": round(total_costs, 2),
        })

    return equity_curve, trades
